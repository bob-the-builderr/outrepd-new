"""Writes lib/country_names.g.dart from Unicode CLDR.

Accounts store a country as its two-letter ISO code ("EG"). This turns the
CLDR territory names for the app's thirteen languages into one Dart map per
language, so a screen can say "مصر" or "Ägypten" instead of the code.

Needs the npm package cldr-localenames-modern unpacked somewhere:

    curl -sSfL "$(npm view cldr-localenames-modern dist.tarball)" | tar xz

Run from the Flutter project root:

    python tool/gen_country_names.py path/to/package
"""

import io
import json
import os
import re
import sys

LANGUAGES = ['de', 'en', 'es', 'fr', 'hi', 'id', 'it', 'ja', 'ko', 'pt',
             'ru', 'tr', 'zh']

# Two-letter codes CLDR lists that are not countries anyone lives in, plus CQ
# (Sark), which CLDR names only in English so far.
NOT_COUNTRIES = {'EU', 'EZ', 'UN', 'QO', 'ZZ', 'XA', 'XB', 'CQ'}


def names(package, lang):
    path = os.path.join(package, 'main', lang, 'territories.json')
    with io.open(path, encoding='utf-8') as f:
        data = json.load(f)
    territories = data['main'][lang]['localeDisplayNames']['territories']
    return {
        code: name
        for code, name in territories.items()
        if re.fullmatch(r'[A-Z]{2}', code) and code not in NOT_COUNTRIES
    }


def dart_string(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    package = sys.argv[1]
    version = json.load(io.open(os.path.join(package, 'package.json')))['version']
    out = [
        '// GENERATED by tool/gen_country_names.py from CLDR '
        f'{version}. Do not edit by hand.',
        '//',
        '// ignore_for_file: lines_longer_than_80_chars',
        '',
        '/// Country names by language, keyed by two-letter ISO code.',
        'const kCountryNames = <String, Map<String, String>>{',
    ]
    for lang in LANGUAGES:
        out.append(f"  '{lang}': {{")
        for code, name in sorted(names(package, lang).items()):
            out.append(f"    '{code}': {dart_string(name)},")
        out.append('  },')
    out.append('};')
    out.append('')
    with io.open('lib/country_names.g.dart', 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
