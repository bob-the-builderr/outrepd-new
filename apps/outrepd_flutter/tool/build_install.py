"""Joins the server's SQL into one file that can be pasted in one go.

There is no psql on this machine, so the database is changed by pasting into
the Supabase SQL editor. Three pastes in the right order is three chances to
paste the wrong one, or to forget the third; this makes it one.

    python tool/build_install.py

`test/sql_lint_test.dart` fails if the parts have changed since this last ran,
because a stale installer is worse than no installer: it installs something
nobody has read.
"""

import io
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The order they depend on each other. subscriptions.sql comes first because
# the sets policy in schema.sql calls has_pro(); social.sql comes before
# duel.sql because find_opponent_set has to check friendships to honour
# 'friends only'. account.sql comes after every table, because my_data()
# hands back all of them and a SQL function's tables must already exist.
PARTS = ['subscriptions.sql', 'schema.sql', 'ladder.sql', 'social.sql',
         'duel.sql', 'notify.sql', 'push.sql', 'live.sql', 'seasons.sql',
         'testers.sql', 'adventure.sql', 'account.sql',
         'lockdown.sql']

HEADER = """-- OUTREPD — everything the server needs, in one paste.
--
-- Generated by joining the files in `supabase/` in the order they depend on
-- each other. Paste it into the Supabase SQL editor and run it once.
-- Re-running is safe: every object is created with `if not exists`, `or
-- replace`, or dropped first.
--
-- Regenerate with:  python tool/build_install.py
--
-- Afterwards, from the app folder:
--
--   flutter test test/ladder_server_test.dart  --dart-define=...   (485 cases)
--   flutter test test/duel_server_test.dart    --dart-define=...   (a real duel)
"""

RULE = '-- ' + '=' * 72


def main():
    out = [HEADER]
    for part in PARTS:
        path = os.path.join(HERE, 'supabase', part)
        body = io.open(path, encoding='utf-8').read().replace('\r\n', '\n')
        out.append('\n%s\n-- %s\n%s\n\n%s' % (RULE, part, RULE, body.strip()))

    text = '\n'.join(out) + '\n'
    target = os.path.join(HERE, 'supabase', 'install.sql')
    io.open(target, 'w', encoding='utf-8', newline='\n').write(text)
    print('%s — %d lines from %s' %
          (target, text.count('\n'), ', '.join(PARTS)))


if __name__ == '__main__':
    main()
