// Writes supabase/functions/push/messages.ts: the words each push is sent
// in, taken from the app's own translations, so a push says exactly what the
// notice says when it is opened — in the same language.
//
//     dart run tool/build_push_messages.dart
//
// test/push_messages_test.dart fails when the translations have changed and
// this has not been run since.
import 'dart:convert';
import 'dart:io';

/// The strings a push needs, one title and one body per kind of notice.
const pushKeys = [
  'nRacedTitle',
  'nRacedHeld',
  'nRacedBeaten',
  'nFriendTitle',
  'nFriendBody',
  'nFriendOkTitle',
  'nFriendOkBody',
  'nChallengedTitle',
  'nChallengedBody',
  'nLiveTitle',
  'nLiveBody',
  'nPassedTitle',
  'nPassedBody',
];

Map<String, Map<String, String>> pushMessages() {
  final files =
      Directory('lib/l10n')
          .listSync()
          .whereType<File>()
          .where((f) => RegExp(r'app_[a-z]+\.arb$').hasMatch(f.path))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = <String, Map<String, String>>{};
  for (final file in files) {
    final language = RegExp(r'app_([a-z]+)\.arb$').firstMatch(file.path)![1]!;
    final arb = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
    out[language] = {for (final key in pushKeys) key: arb[key] as String};
  }
  return out;
}

const header = '''// Generated by tool/build_push_messages.dart from lib/l10n/app_*.arb.
// Do not edit: change the translations and run it again.
//
// The words a push is written in — the strings the app shows for the same
// notice, in every language the app ships in.
export const messages: Record<string, Record<string, string>> = ''';

void main() {
  final json = const JsonEncoder.withIndent('  ').convert(pushMessages());
  File(
    'supabase/functions/push/messages.ts',
  ).writeAsStringSync('$header$json;\n');
  stdout.writeln('wrote supabase/functions/push/messages.ts');
}
